// Writes src/gui/icon-names.ts from the SDK's IconName union. Run after updating @opencode/plugin: `bun run icons`.
const source = await Bun.file(
  new URL("../node_modules/@opencode/plugin/dist/gui/icon-name.d.ts", import.meta.url),
).text()
const names = [...source.matchAll(/"([a-z0-9-]+)"/g)].map((match) => match[1]!)

await Bun.write(
  new URL("../src/gui/icon-names.ts", import.meta.url),
  `// Generated by scripts/icon-names.ts from the SDK's IconName: do not edit.
import type { IconName } from "@opencode/plugin/gui"

export const ICON_NAMES = [
${names.map((name) => `  "${name}",`).join("\n")}
] as const satisfies readonly IconName[]

// Fails to compile when the SDK has an icon this list lacks.
export const ICON_NAMES_COMPLETE: [Exclude<IconName, (typeof ICON_NAMES)[number]>] extends [never] ? true : false = true
`,
)
console.log(`${names.length} icons`)
